#!/usr/bin/env python3
"""Project-owned IDs, not legacy compatibility; deterministic fail-closed generator."""
import hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parents[2]
f=json.loads((root/'analysis/plugin-parameter-catalog.json').read_text())['files']
params={s['attributes']['name']+'/'+p['attributes']['name']:p['attributes'] for s in f['remotedevice.xml']['parameter_sets'] for p in s['children']}
rows=[]
for r in f['automation.xml']['automation']:
    p=params.get(r['Parameter']); part=int(r['Part']); index=int(r['Index'])
    assert 1<=part<=16 and 0<=index<0x100000
    lo,hi,default=(float(p[k]) for k in ('minValue','maxValue','defaultValue')) if p else (0.,1.,0.)
    assert lo < hi and lo<=default<=hi
    midi=int(p['controllerindex']) if p and p.get('defaultmessage')=='cc' and 0<=lo<=hi<=127 else -1
    assert -1<=midi<=127
    rows.append((0x10000000+index,part,r['Parameter'],lo,hi,default,midi,bool(p)))
rows.sort()
assert len(rows)==2672 and len(set(r[0] for r in rows))==2672
out=['// Generated by generate_catalog.py; do not hand edit.', '#pragma once', '#include <array>', '#include <cstdint>', 'namespace VirusRework {', 'struct ParamSpec { uint32_t id; int part; const char* name; double minimum, maximum, initial; int midiCC; bool resolved; };', 'inline constexpr std::array<ParamSpec,2672> kCatalog{{']
for id,part,name,lo,hi,default,midi,resolved in rows:
    out.append(f' {{{id}u,{part},{json.dumps(name)},{lo},{hi},{default},{midi},{str(resolved).lower()}}},')
out+=['}};', 'inline constexpr uint32_t kConnectionStatus=0x20000000;', '}']
(pathlib.Path(__file__).parent/'catalog.h').write_text('\n'.join(out)+'\n')
(pathlib.Path(__file__).parent/'catalog-provenance.json').write_text(json.dumps({'source_sha256':{k:f[k]['sha256'] for k in ('remotedevice.xml','automation.xml')},'policy':'Development IDs = 0x10000000 + XML automation Index; legacy VST3 IDs unverified. Unresolved Softknobs normalized 0..1 read-only. Numeric plain ranges only; mode conditions/value lists not implemented.','parameters':len(rows),'resolved':sum(r[-1] for r in rows),'unresolved':sorted(set(r[2] for r in rows if not r[-1]))},indent=2)+'\n')
